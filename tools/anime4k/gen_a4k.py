#!/usr/bin/env python3
"""Converts Anime4K's mpv-format GLSL into this project's output-shader form.

Scripted rather than hand-copied: the S variant alone carries ~90 mat4 weight
literals, and a single mistyped digit would be invisible in review and would
show up only as a subtly wrong image.

The mapping is mechanical:
  MAIN_texOff(vec2(dx,dy))      -> texture(textureSrc, passUV + vec2(dx,dy)*texel)
  <name>_texOff(vec2(dx,dy))    -> texture(textureSrc, passUV + vec2(dx,dy)*texel)
  MAIN_tex(MAIN_pos)            -> texture(textureSrc2, passUV)
  vec4 hook() { ... return X; }  -> void outputShader() { ... colorOut0 = X; }

Each //!HOOK block becomes one pass. The pass that BINDs two textures (the
final residual one) reads the original through textureSrc2, so the bindings
stay fixed across passes and the descriptor layout does not change per pass.
"""
import re
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
text = open(src_path, encoding="utf-8").read()

# Split on //!DESC, which starts every pass.
chunks = re.split(r'^//!DESC ', text, flags=re.M)[1:]

passes = []
for chunk in chunks:
    lines = chunk.split("\n")
    desc = lines[0].strip()
    binds = [l.split(" ", 1)[1].strip() for l in lines if l.startswith("//!BIND")]
    save = next((l.split(" ", 1)[1].strip() for l in lines if l.startswith("//!SAVE")), "MAIN")
    body = "\n".join(l for l in lines[1:] if not l.startswith("//!"))

    # The sampler the convolution reads is whatever this pass declares LAST as
    # its data input; the original frame, when also bound, is the residual term.
    primary = binds[-1] if binds else "MAIN"

    # texOff -> explicit texel offset against our own resolution uniform.
    body = re.sub(
        r'\b\w+_texOff\(vec2\(([^)]*)\)\)',
        r'texture(textureSrc, passUV + vec2(\1) * anubisTexel)',
        body)
    # The residual read of the untouched original.
    body = body.replace("MAIN_tex(MAIN_pos)", "texture(textureSrc2, passUV)")

    body = body.replace("vec4 hook() {", "void outputShader()\n{\n\tvec2 anubisTexel = 1.0 / max(textureSrcResolution, vec2(1.0));")
    body = re.sub(r'return\s+(.+?);', r'colorOut0 = \1;', body, flags=re.S)

    passes.append((desc, primary, save, body.strip()))

mit = "\n".join(l for l in text.split("\n")[:22] if l.startswith("//"))

with open(out_path, "w", encoding="utf-8") as f:
    f.write("// GENERATED by gen_a4k.py from Anime4K_Restore_CNN_S.glsl - do not hand-edit.\n")
    f.write("// Regenerate rather than patch, so the weights always match upstream.\n//\n")
    f.write("// Upstream licence, reproduced as the MIT terms require:\n")
    f.write(mit + "\n\n")
    for i, (desc, primary, save, body) in enumerate(passes):
        f.write(f"// Pass {i}: {desc}\n// reads {primary} -> writes {save}\n")
        f.write(f"const std::string RendererOutputShader::s_a4k_restore_pass{i}_source =\nR\"(\n{body}\n)\";\n\n")

print(f"{len(passes)} passes written to {out_path}")
for i, (desc, primary, save, _) in enumerate(passes):
    print(f"  pass {i}: {primary} -> {save}   {desc}")
